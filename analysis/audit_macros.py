"""LaTeX macros for the second-review audits (results/runs/stage1-audits/*.json → paper/generated/numbers_audit.tex).

    python analysis/audit_selection.py --work $PATHJEV_WORK > results/runs/stage1-audits/selection.json
    python analysis/audit_rerun.py --work $PATHJEV_WORK > results/runs/stage1-audits/rerun.json
    python analysis/audit_macros.py --work $PATHJEV_WORK

Also counts the Gen-SFT training examples (one per decision of the Stage 1 training mix) and the passes made by the
evaluated checkpoints (trainer_state.json), so that no budget number is typed by hand.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def fmt_int(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--work", required=True, type=Path)
    args = ap.parse_args()
    d = REPO / "results" / "runs" / "stage1-audits"
    sel, rr = json.loads((d / "selection.json").read_text()), json.loads((d / "rerun.json").read_text())
    m = {}
    runs = [k for k in sel if not k.startswith("grid_")]
    m["AuditSelSameAll"] = "yes" if all(sel[r]["same"] for r in runs) else "no"
    m["AuditSelRuns"] = str(len(runs))
    m["AuditSelGridSame"] = "yes" if all(sel[f"grid_{a}_a"] == sel[f"grid_{a}_b"] for a in ("jev", "sft")) else "no"
    # rerun on another GPU type (stored H100 vs A3 L40), main Choice, seed mean
    sets = [s for seed in rr["per_seed"].values() for s in seed["sets"].values()]
    m["AuditRerunMaxDp"] = f"{max(s['max_abs_dp'] for s in sets):.2f}"
    m["AuditRerunMinAgree"] = f"{100 * min(s['argmax_agree'] for s in sets):.1f}"
    m["AuditRerunMaxMacroDiff"] = f"{max(abs(rr[g][k]['stored'] - rr[g][k]['rerun']) for g in ('clean', 'unseen', 'in_domain') for k in ('balanced_accuracy', 'ece')):.3f}"
    m["AuditEosMinProb"] = f"{2.718281828 ** (-rr['eos_logp']['max_abs']):.4f}"
    m["AuditEosShareExact"] = f"{100 * (1 - rr['eos_logp']['n_nonzero'] / rr['eos_logp']['n']):.0f}"
    m["AuditEosMaxDp"] = f"{rr['max_abs_p_primary_minus_eos']:.1e}".replace("e-0", "\\times10^{-").replace("e-", "\\times10^{-") + "}"
    # Gen-SFT examples per pass and passes at the evaluated checkpoint
    n_dec = sum(len(json.loads(l)["decisions"]) for l in (args.work / "mixes" / "stage1-p" / "train.jsonl").open() if l.strip())
    m["SFTExamplesPerPass"] = fmt_int(n_dec)
    best = json.loads((REPO / "results" / "runs" / "stage1-config" / "sft.json").read_text())["best_run"]
    ck = Path((args.work / "runs" / f"train_{best}" / "selection" / "best.txt").read_text().strip())
    m["SFTPassesAtCkpt"] = f"{json.loads((ck / 'trainer_state.json').read_text())['epoch']:.2f}"
    bad = [k for k in m if not k.isalpha()]
    if bad:
        raise ValueError(f"macro names must be letters only: {bad}")
    out = REPO / "paper" / "generated" / "numbers_audit.tex"
    out.write_text("% generated by analysis/audit_macros.py — do not edit\n"
                   + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())) + "\n")
    print(f"{len(m)} macros -> {out}")


if __name__ == "__main__":
    main()
