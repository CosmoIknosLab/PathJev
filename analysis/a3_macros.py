"""LaTeX macros for amendment A3.2–A3.5 (results/runs/stage1-a3/summary.json → paper/generated/numbers_a3.tex).

    python analysis/a3_macros.py

Names are letters only (\\AThree...). Values are read from the A3 summary; nothing is typed by hand.
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
GROUPS = {"clean": "Clean", "unseen": "Unseen", "in_domain": "InDom", "seen_source": "Seen"}
METRICS = {"balanced_accuracy": "Bacc", "ece": "Ece", "nll": "Nll"}
ARMS = {"jev": "PJ", "sft": "SFT", "omnimedjev": "OMJ"}


def f3(x: float) -> str:
    return f"{x:.3f}"


def main() -> None:
    s = json.loads((REPO / "results" / "runs" / "stage1-a3" / "summary.json").read_text())
    m = {}
    # A3.3 OmniMed-Jev at 896
    for g, gk in GROUPS.items():
        for met, mk in METRICS.items():
            m[f"AThreeOMJNineSix{gk}{mk}"] = f3(s["A3.3"]["896"][g][met])
    # A3.4 Gen-SFT read-outs
    for var, vk in (("primary", "Sum"), ("lennorm", "Len")):
        for g, gk in GROUPS.items():
            if g not in s["A3.4"][var]:
                continue
            for met, mk in METRICS.items():
                m[f"AThreeSFT{vk}{gk}{mk}"] = f3(s["A3.4"][var][g][met])
    m["AThreeSFTRerunMaxDiff"] = f"{s['A3.4']['max_abs_diff_primary_rerun_vs_stored']:.2f}"
    m["AThreeSFTRerunAgree"] = f"{100 * s['A3.4']['argmax_agreement_primary_rerun_vs_stored']:.1f}"
    # A3.5 candidate order
    for arm, ak in ARMS.items():
        r = s["A3.5"][arm]
        m[f"AThreePerm{ak}N"] = str(r["permutations"])
        for met, mk in (("balanced_accuracy", "Bacc"), ("ece", "Ece")):
            for stat, sk in (("min", "Min"), ("max", "Max"), ("sd", "SD")):
                m[f"AThreePerm{ak}{mk}{sk}"] = f3(r[met][stat])
        m[f"AThreePerm{ak}TV"] = f3(r["mean_tv_to_original"])
        m[f"AThreePerm{ak}Flip"] = f"{100 * r['argmax_flip_rate']:.1f}"
    bad = [k for k in m if not k.isalpha()]
    if bad:
        raise ValueError(f"macro names must be letters only: {bad}")
    out = REPO / "paper" / "generated" / "numbers_a3.tex"
    out.write_text("% generated by analysis/a3_macros.py — do not edit\n"
                   + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())) + "\n")
    print(f"{len(m)} macros -> {out}")


if __name__ == "__main__":
    main()
