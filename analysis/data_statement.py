"""Data statement table for the paper (paper/generated/data_statement.tex), from data/registry.csv.

    python analysis/data_statement.py --work $PATHJEV_WORK

Writes data_statement.tex and tab_testsets.tex (states, classes, bootstrap groups per test set, from
$PATHJEV_WORK/eval_sets/stage1-test). Data-statement rows are the datasets used in Stage 1 (D-029); every field shown is read from the registry and the
script fails if a dataset is missing or its role was not finalised (role must start with "STAGE1").
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from pathjev.groups import excluded_state_ids, state_group  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
USED = [("SPIDER", "SPIDER (4 organs)"), ("BRACS", "BRACS"), ("SICAPv2", "SICAPv2"),
        ("HepatoBench", "HepatoBench"), ("HiESD", "HiESD")]


def tex(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def first_doi(s: str) -> str:
    m = re.search(r"(?:doi:|DOI )?(10\.\d{4,9}/[^\s;,)]+)", s)
    return m.group(1).rstrip(".") if m else re.search(r"arXiv:\S+", s).group(0)


def licence(s: str) -> str:
    """Licence recorded in the registry; on a documented conflict, the most restrictive one (registry rule)."""
    found = [f.replace("CC-BY-4.0", "CC BY 4.0") for f in re.findall(r"CC BY(?:-NC)?(?:-SA)?(?:-ND)? 4\.0|CC-BY-4\.0", s)]
    if not found:
        raise ValueError(f"no licence in: {s[:80]}")
    if s.startswith("CONFLICT"):
        return ("CC BY-NC 4.0" if any("NC" in f for f in found) else found[0]) + "$^\\ddagger$"
    return found[0]


def access(s: str) -> str:
    s = s.lower()
    if "gated" in s:
        return "gated (accept conditions)"
    if "registration" in s and "no registration" not in s:
        return "registration, terms of use"
    return "open download"


TEST_SETS = [("hepatobench", "HepatoBench", "liver", "clean, unseen domain", "image$^\\S$"),
             ("hiesd", "HiESD", "stomach", "clean, unseen domain", "patient"),
             ("bracs", "BRACS", "breast", "clean, in domain", "patient"),
             ("sicapv2", "SICAPv2", "prostate", "clean, in domain", "patient"),
             ("spider-colorectal", "SPIDER colorectal", "colon", "seen source", "slide"),
             ("spider-thorax", "SPIDER thorax", "lung", "seen source", "slide"),
             ("spider-breast", "SPIDER breast", "breast", "seen source", "slide"),
             ("spider-skin", "SPIDER skin", "skin", "seen source", "slide")]


def test_sets(work: Path) -> str:
    d = work / "eval_sets" / "stage1-test"
    info = json.loads((d / "info.json").read_text())["sets"]
    out = [r"\begin{tabular}{@{}lllrrrl@{}}", r"\toprule",
           r"Set & Organ & Role & Classes & States & Groups & Group unit \\", r"\midrule"]
    excluded = excluded_state_ids()
    full = d.parent / "stage1-test-full"
    for key, name, organ, role, unit in TEST_SETS:
        i = info[key]
        states = [json.loads(l) for l in (d / f"{key}.jsonl").open() if l.strip()]
        states = [s for s in states if s["state_id"] not in excluded]          # duplicates of training images
        groups = {state_group(s) for s in states}                               # patient for HiESD
        n_avail = i["available"] - sum(1 for l in (full / f"{key}.jsonl").open()
                                       if l.strip() and json.loads(l)["state_id"] in excluded)
        used = f"{len(states):,}".replace(",", "{,}")
        if len(states) < n_avail:
            used += f" of {n_avail:,}".replace(",", "{,}")
        n_groups = f"{len(groups):,}".replace(",", "{,}")
        out.append(f"{name} & {organ} & {role} & {len(i['classes'])} & {used} & {n_groups} & {unit} \\\\")
    return "\n".join(out + [r"\bottomrule", r"\end{tabular}"]) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--work", required=True, type=Path)
    args = ap.parse_args()
    (REPO / "paper" / "generated" / "tab_testsets.tex").write_text(
        "% generated by analysis/data_statement.py — do not edit\n" + test_sets(args.work))
    rows = list(csv.DictReader((REPO / "data" / "registry.csv").open()))
    out = [r"\begin{tabular}{@{}>{\raggedright}p{2.5cm}>{\raggedright}p{3.4cm}>{\raggedright}p{2.2cm}>{\raggedright}p{2.3cm}>{\raggedright\arraybackslash}p{3.7cm}@{}}", r"\toprule",
           r"Dataset & DOI / ID & Licence & Access & Role in this work \\", r"\midrule"]
    for key, short in USED:
        r = next((r for r in rows if r["name"].startswith(key) or r["name"].strip('"').startswith(key)), None)
        if r is None:
            raise KeyError(key)
        if not r["role"].startswith("STAGE1"):
            raise ValueError(f"{key}: role not finalised in registry: {r['role'][:60]}")
        role = r["role"].split(":", 1)[1].split(" - ")[0].strip()
        role = re.sub(r"\(\s*\)", "", re.sub(r"[,;]?\s*D-\d{3}\s*;?", "", role)).strip()
        out.append(f"{tex(short)} & \\nolinkurl{{{first_doi(r['version_or_doi'])}}} & {licence(r['licence'])} & "
                   f"{access(r['access_conditions'])} & {tex(role)} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    dst = REPO / "paper" / "generated" / "data_statement.tex"
    dst.write_text("% generated by analysis/data_statement.py from data/registry.csv — do not edit\n" + "\n".join(out) + "\n")
    print(dst)


if __name__ == "__main__":
    main()
